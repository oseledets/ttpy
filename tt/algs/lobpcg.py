r"""Fixed-rank LOBPCG-style solver for Hermitian positive-definite TT systems.

``lobpcg_solve`` minimizes

.. math::

    E(x) = \tfrac12 \langle x, A x\rangle - \Re\langle f, x\rangle

on the manifold of tensors having the rank profile of ``x0``.  It uses a
one-site alternating sweep.  At site ``k`` the local correction equation is
solved by augmented PCG in the affine space generated by

``[current core, preconditioned residual, transported previous direction]``.

There is one remembered direction per TT core.  A direction saved on the
previous sweep represents the ambient tensor ``V_old p``; before reuse it is
projected into the new one-core chart as ``V_new.H V_old p``.  The overlap
factorizes into one left and one right frame contraction, so neither the full
tensor nor a dense tangent chart is formed.

This is deliberately a separate algorithm from :func:`tt.amen_solve`.  AMEn
enriches TT bases and adapts ranks.  This solver never enriches, truncates, or
uses an SVD: every bond dimension stays equal to the corresponding dimension
of ``x0``.

Notes
-----
The name follows the LOBPCG three-term idea, but the problem is a linear SPD
system rather than an eigenproblem.  The stopping quantity is the norm of the
horizontal projected energy gradient, divided by ``||f||``.  It certifies a
stationary point of the *fixed-rank* problem; it is not the same as the full
linear residual when the selected ranks cannot represent the exact solution.
Set ``check_true_res=True`` to report the latter as well.

Backend agnostic: every array operation goes through :mod:`tt.backend`, so the
solver runs unchanged on numpy and on torch (CPU or GPU) cores; ``A`` and ``f``
are brought to the backend of ``x0``, which owns the answer.  The only numpy in
here is the host-side bookkeeping (ranks, convergence tests, printing) and the
compiled float64 local kernel, which is one branch of a dispatch whose other
branch is the pure implementation.
"""

